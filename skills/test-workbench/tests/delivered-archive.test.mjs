import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp, rm, writeFile, readFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {FileSource, command} from '../scripts/workspace-sources.mjs';
import {verifyDeliveredArchive} from '../scripts/verify-delivered-archive.mjs';
import {FakeGitHub} from './fake-github.mjs';
import {archiveFixture, initFixtureRepo} from './delivered-archive-fixture.mjs';

const script=fileURLToPath(new URL('../scripts/verify-delivered-archive.mjs',import.meta.url));
test('verification from committed files detects an ignored local round and confirms recovery from a fresh clone',async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),'delivered-history-'));
  t.after(()=>rm(root,{recursive:true,force:true}));
  const repo=path.join(root,'source'),clean=path.join(root,'clean'),restored=path.join(root,'restored'),input=path.join(root,'expected.json');
  const {definitions,state,expected}=archiveFixture();
  await writeFile(input,JSON.stringify(expected));
  await initFixtureRepo(repo);
  const source=new FileSource({repoRoot:repo});
  await source.initialize();await source.write(0,definitions);await source.commit(1);
  await source.write(1,state);
  const {generation}=JSON.parse(await readFile(path.join(repo,'testing/testflow/workspace.json'),'utf8'));
  await writeFile(path.join(repo,'.git/info/exclude'),`/testing/testflow/snapshots/${generation}/\n`);
  const run=repoRoot=>command(process.execPath,[script,'--repo-root',repoRoot,'--expect',input]);
  await assert.rejects(run(repo),/old.*clean checkout/);
  await command('git',['clone','--quiet','--no-local',repo,clean]);
  await assert.rejects(run(clean),/Round old is missing/);
  assert.deepEqual((await source.read()).state,state);
  await writeFile(path.join(repo,'.git/info/exclude'),'');
  await source.commit(2);
  await command('git',['clone','--quiet','--no-local',repo,restored]);
  const verified=JSON.parse(await run(restored));
  assert.equal(verified.revision,2);
  assert.match(verified.rounds[0].link,/round=old.*observation=original-observation/);
  assert.deepEqual((await new FileSource({repoRoot:restored}).read()).state,state);
  assert.equal(await command('git',['-C',restored,'status','--porcelain']),'');
  await assert.rejects(verifyDeliveredArchive(new FileSource({repoRoot:restored}),[{...expected[0],source:'wrong'}]),/Round old: source differs/);
  const env={...process.env,PATH:root};
  await assert.rejects(command(process.execPath,[script,'--repo-root',restored,'--expect',input],{env}),/old.*git unavailable/);
  await assert.rejects(command(process.execPath,[script,'--repo','owner\/repo','--expect',input],{env}),/old.*gh unavailable/);
});

test('published Issue reads identify the missing index, round snapshot and access errors and recover without writes',async()=>{
  const {definitions,state,expected}=archiveFixture(),api=new FakeGitHub(),source=api.source();
  await assert.rejects(verifyDeliveredArchive(source,expected),/old.*index or publication is missing/);
  await source.initialize();await source.write(0,definitions);await source.write(1,state);
  const loaded=await source.load(),index=api.items.get(source.index),writes=api.writes();
  api.items.delete(source.index);
  await assert.rejects(verifyDeliveredArchive(source,expected),/old.*index Issue #1 is missing or inaccessible/);
  api.items.set(source.index,index);
  const [commentId]=loaded.manifest.rounds.find(ref=>ref.key===JSON.stringify(['round','old'])).comments;
  const comment=api.comments.get(commentId);
  api.comments.delete(commentId);
  await assert.rejects(verifyDeliveredArchive(source,expected),/round snapshot.*old.*missing, inaccessible or invalid/);
  api.comments.set(commentId,comment);
  api.fail=(method,route)=>method==='GET'&&route.endsWith('/comments/'+commentId)?'before':null;
  await assert.rejects(verifyDeliveredArchive(source,expected),/round snapshot.*old.*network failure/);
  api.fail=null;
  const verified=await verifyDeliveredArchive(api.source(),expected);
  assert.equal(verified.rounds[0].roundId,'old');
  assert.equal(verified.rounds[0].verdict,'failed');
  assert.match(verified.rounds[0].link,/round=old.*observation=original-observation/);
  assert.deepEqual((await source.read()).state,state);
  assert.equal(api.writes(),writes);
});
